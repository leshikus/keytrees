#!/usr/bin/env python3
"""Merge the omn engine runs into data/omn and write the article's table fragments.

    scripts/omn_tables.py <cells-dir>   merge <cells-dir>/{worst,average,minmax}_<m>_<n>.csv
                                        and their logs into data/omn, then write the tables
    scripts/omn_tables.py               only write the tables from data/omn

The tables go to articles/omn-trees/tables.tex.
"""
from __future__ import annotations

import csv
import sys
from collections import defaultdict
import os
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data" / "omn"
OUT = Path(os.environ.get("CODES_DIR", ROOT.parent / "codes")) / "articles" / "omn-trees" / "tables.tex"
CELLS = [(m, n) for n in range(4) for m in range(n + 1)]
KINDS = {"worst": "W", "average": "total", "minmax": "total"}
OMAX = 4000


def merge(cells: Path) -> None:
    DATA.mkdir(parents=True, exist_ok=True)
    limits = []
    for kind in KINDS:
        rows, header = [], None
        for m, n in CELLS:
            f = cells / f"{kind}_{m}_{n}.csv"
            if not f.exists():
                continue
            with f.open() as fh:
                r = list(csv.reader(fh))
            header = r[0]
            body = r[1:]
            rows += body
            log = cells / f"{kind}_{m}_{n}.log"
            text = log.read_text() if log.exists() else ""
            last = int(body[-1][0]) if body else 0
            if "stopped after" in text:
                stop = "one o took too long"
            elif last >= OMAX:
                stop = "reached the cap o = 4000"
            else:
                stop = "overall time limit of the run"
            limits.append([kind, m, n, last, body[-1][-1] if body else "", stop])
        with (DATA / f"{kind}.csv").open("w", newline="") as fh:
            w = csv.writer(fh, lineterminator="\n")
            w.writerow(header)
            w.writerows(rows)
    single = sorted(
        (f.read_text().strip().split(",") for f in cells.glob("single/*.row") if f.stat().st_size),
        key=lambda r: int(r[0]),
    )
    with (DATA / "worst_3_3_single.csv").open("w", newline="") as fh:
        w = csv.writer(fh, lineterminator="\n")
        w.writerow(["o", "m", "n", "W", "hamming", "pair", "seconds"])
        w.writerows(single)
    with (DATA / "limits.csv").open("w", newline="") as fh:
        w = csv.writer(fh, lineterminator="\n")
        w.writerow(["quantity", "m", "n", "o_max", "seconds_last_o", "stopped_by"])
        w.writerows(limits)


def load(kind: str) -> dict[tuple[int, int], dict[int, dict[str, str]]]:
    out: dict[tuple[int, int], dict[int, dict[str, str]]] = defaultdict(dict)
    with (DATA / f"{kind}.csv").open() as fh:
        for row in csv.DictReader(fh):
            out[int(row["m"]), int(row["n"])][int(row["o"])] = row
    return out


def complete_tree_total(o: int) -> int:
    level = o.bit_length() - 1
    return o * (level + 2) - 2 ** (level + 1)


def max_objects(col: dict[int, dict[str, str]]) -> dict[int, int]:
    """N(q) = largest o with W(o) <= q, for the q settled by the computed range."""
    top = max(col)
    w = {o: int(r["W"]) for o, r in col.items()}
    res = {}
    for q in range(0, w[top]):
        res[q] = max(o for o in w if w[o] <= q)
    return res


def tables() -> str:
    worst, minmax = load("worst"), load("minmax")
    lines = ["% Generated by scripts/omn_tables.py from data/omn; do not edit."]
    top = max(worst[3, 3])
    with (DATA / "worst_3_3_single.csv").open() as fh:
        single = {int(r["o"]) for r in csv.DictReader(fh)}
    missing = [o for o in range(top + 1, 266) if o not in single]
    spans: list[list[int]] = []
    for o in missing:
        if spans and spans[-1][1] == o - 1:
            spans[-1][1] = o
        else:
            spans.append([o, o])
    text = ", ".join(f"${a}$" if a == b else f"${a}$--${b}$" for a, b in spans) or "none"
    lines += [
        rf"\newcommand{{\omnDeppeTop}}{{{top}}}",
        rf"\newcommand{{\omnDeppeSingles}}{{{len(single)}}}",
        rf"\newcommand{{\omnDeppeMissing}}{{{text}}}",
    ]
    head = " & ".join(f"$({m},{n})$" for m, n in CELLS)
    # Table: W(o, m, n), o = 1..32.
    lines += [
        r"\begin{table}[ht]\centering\footnotesize\renewcommand{\arraystretch}{0.93}",
        r"\caption{$W(o,m,n)$ for $o\le 32$; the column heads are $(m,n)$.}\label{tab:worst}",
        r"\begin{tabular}{r" + "r" * len(CELLS) + "}",
        r"$o$ & " + head + r" \\ \hline",
    ]
    for o in range(1, 33):
        lines.append(f"{o} & " + " & ".join(worst[c][o]["W"] for c in CELLS) + r" \\")
    lines += [r"\end{tabular}", r"\end{table}", ""]
    # Table: N(q) for m = n.
    cols = [(1, 1), (2, 2), (3, 3), (1, 2), (1, 3), (2, 3)]
    nq = {c: max_objects(worst[c]) for c in cols}
    qs = sorted(set().union(*[set(v) for v in nq.values()]))
    qs = [q for q in qs if any(nq[c].get(q, 0) >= 2 for c in cols)]
    lines += [
        r"\begin{table}[ht]\centering\footnotesize\renewcommand{\arraystretch}{0.93}",
        r"\caption{$N_{m,n}(q)$, the largest $o$ with $W(o,m,n)\le q$, for the $q$ settled by "
        r"the computed range; a dash marks $q$ beyond it.}\label{tab:nq}",
        r"\begin{tabular}{r" + "r" * len(cols) + "}",
        r"$q$ & " + " & ".join(f"$({m},{n})$" for m, n in cols) + r" \\ \hline",
    ]
    for q in qs:
        lines.append(f"{q} & " + " & ".join(str(nq[c].get(q, "--")) for c in cols) + r" \\")
    lines += [r"\end{tabular}", r"\end{table}", ""]
    # Table: excess of the minmax average over T(o) + n o.
    excess: dict[int, set[int]] = defaultdict(set)
    common = min(max(minmax[c]) for c in CELLS if c[0] >= 1)
    for c in CELLS:
        if c[0] == 0:
            continue
        for o in range(2, common + 1):
            excess[o].add(int(minmax[c][o]["total"]) - complete_tree_total(o) - c[1] * o)
    nonzero = [(o, next(iter(e))) for o, e in sorted(excess.items()) if e != {0} and len(e) == 1]
    lines += [
        r"\begin{table}[ht]\centering\footnotesize\renewcommand{\arraystretch}{0.93}",
        r"\caption{The $o\le " + str(common) + r"$ with $A^*(o,m,n) > T(o)+no$ and the excess "
        r"$A^*(o,m,n)-T(o)-no$, the same for all six $(m,n)$ with $m\ge 1$ in this range.}"
        r"\label{tab:excess}",
        r"\begin{tabular}{" + "r" * 2 + "}",
        r"$o$ & excess \\ \hline",
    ]
    lines += [f"{o} & {e}" + r" \\" for o, e in nonzero]
    lines += [r"\end{tabular}", r"\end{table}", ""]
    # Table: limits.
    lines += [
        r"\begin{table}[ht]\centering\footnotesize\renewcommand{\arraystretch}{0.93}",
        r"\caption{Computed ranges: largest $o$ and the time for that $o$ alone "
        r"(memo kept from smaller $o$).}\label{tab:limits}",
        r"\begin{tabular}{lrrrrl}",
        r"quantity & $m$ & $n$ & $o_{\max}$ & s & stopped by \\ \hline",
    ]
    with (DATA / "limits.csv").open() as fh:
        for row in csv.DictReader(fh):
            q = {"worst": "$W$", "average": "$A$", "minmax": "$A^*$"}[row["quantity"]]
            lines.append(
                f"{q} & {row['m']} & {row['n']} & {row['o_max']} & "
                f"{float(row['seconds_last_o']):.1f} & {row['stopped_by']}" + r" \\"
            )
    lines += [r"\end{tabular}", r"\end{table}", ""]
    return "\n".join(lines)


def main() -> None:
    if len(sys.argv) > 1:
        merge(Path(sys.argv[1]))
    OUT.write_text(tables())


if __name__ == "__main__":
    main()
